#!/usr/bin/env node
/* NEET PYQ assembler (no model). Reads the transcription agents' `entries-NN.jsonl` of one paper, checks them, and writes one source file per chapter:
     rank-pyq-neet-<subject>-<chapter>.js   (global PhysicaRankPyqNeet_<subject>_<chapter>)
   Re-running replaces the entries of the same paper (same id) and keeps the other years, so future PDFs are added the same way.
   usage: node tools/pyq-ingest/neet-assemble.js <workdir> "<exam label>" <year> <expected question count> [--write]
   Optional <workdir>/figs.json: { "<pn>": { "fig": {...}, "sfig": {...} } }  (PhysicaFig specs drawn for the diagram questions).
   Stable ids: neet-<year>-q<NNN>. A question whose normalised text equals an older entry with another id is reported and skipped. */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..', '..');
const [work, label, year, expect, ...flags] = process.argv.slice(2);
if (!work || !label || !year || !expect) { console.error('usage: neet-assemble.js <workdir> "<exam label>" <year> <count> [--write]'); process.exit(2); }
const WRITE = flags.includes('--write');
const CH = JSON.parse(fs.readFileSync(path.join(__dirname, 'neet-chapters.json'), 'utf8')); delete CH.note;
const slug = n => n.toLowerCase().replace(/[^a-z0-9]/g, '');
const fileOf = (s, c) => `rank-pyq-neet-${s.toLowerCase()}-${slug(c)}.js`, globalOf = (s, c) => `PhysicaRankPyqNeet_${s.toLowerCase()}_${slug(c)}`;
const norm = t => String(t).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
const problems = [];
const bad = (pn, m) => problems.push(`Q${pn}: ${m}`);

const rows = [];
for (const f of fs.readdirSync(work).filter(f => /^entries-\d+\.jsonl$/.test(f)).sort())
  for (const l of fs.readFileSync(path.join(work, f), 'utf8').split('\n').filter(Boolean)) { try { rows.push(JSON.parse(l)) } catch { problems.push(`${f}: a line is not JSON: ${l.slice(0, 60)}`) } }
let figs = {}; try { figs = JSON.parse(fs.readFileSync(path.join(work, 'figs.json'), 'utf8')) } catch {}

const seen = new Map(), gaps = [], out = [];
for (const r of rows) {
  if (r.gap) { gaps.push(r.pn); continue }
  if (!Number.isInteger(r.pn)) { problems.push('an entry has no pn'); continue }
  if (seen.has(r.pn)) { bad(r.pn, 'appears twice'); continue } seen.set(r.pn, r);
  const list = CH[r.sub] && Object.values(CH[r.sub]).flat();
  if (!list) bad(r.pn, `unknown subject ${r.sub}`); else if (!list.includes(r.ch)) bad(r.pn, `chapter "${r.ch}" is not in the ${r.sub} list`);
  if (!r.q || !r.st || !r.s) bad(r.pn, 'q, st or s is empty');
  if (!Array.isArray(r.o) || r.o.length !== 4 || r.o.some(x => !String(x).trim())) bad(r.pn, 'needs exactly 4 options');
  if (r.c === null || r.c === undefined) { if (!r.a) bad(r.pn, 'no answer index and no `a` text') } else if (!(r.c >= 0 && r.c <= 3)) bad(r.pn, 'c out of range');
  if (/\bundefined\b|\bNaN\b/.test(JSON.stringify(r))) bad(r.pn, 'contains "undefined" or NaN');
  if (r.dia && !(figs[r.pn] && figs[r.pn].fig)) r._needFig = true;
  if (r.sdia && !(figs[r.pn] && figs[r.pn].sfig)) r._needSfig = true;
  let s = r.s; if (r.flag) s += '\nNote: ' + r.flag.replace(/^Note:\s*/i, '');
  const e = { id: `neet-${year}-q${String(r.pn).padStart(3, '0')}`, pn: r.pn, y: label, tp: r.ch, st: r.st, q: r.q, o: r.o };
  if (r.c !== null && r.c !== undefined) e.c = r.c; else e.a = r.a;
  e.s = s;
  const fg = figs[r.pn]; if (fg?.fig) e.fig = fg.fig; if (fg?.sfig) e.sfig = fg.sfig;
  out.push({ sub: r.sub, ch: r.ch, e });
}
const missing = []; for (let n = 1; n <= +expect; n++) if (!seen.has(n) && !gaps.includes(n)) missing.push(n);

// merge with the files already there
const by = new Map(); for (const x of out) { const k = fileOf(x.sub, x.ch); (by.get(k) || by.set(k, { sub: x.sub, ch: x.ch, add: [] }).get(k)).add.push(x.e) }
const dups = [], written = [];
for (const [file, g] of by) {
  let old = []; const p = path.join(root, file);
  if (fs.existsSync(p)) { const box = {}; vm.runInNewContext(fs.readFileSync(p, 'utf8'), { window: box }); old = box[globalOf(g.sub, g.ch)] || [] }
  const keep = old.filter(o => !g.add.some(a => a.id === o.id));
  const texts = new Map(keep.map(o => [norm(o.q), o.id]));
  const add = g.add.filter(a => { const t = texts.get(norm(a.q)); if (t) { dups.push(`${a.id} equals ${t}`); return false } return true });
  const all = [...keep, ...add].sort((a, b) => (b.id.slice(5, 9) - a.id.slice(5, 9)) || (a.pn - b.pn));
  const body = `/* NEET past-year questions · ${g.sub} · ${g.ch}. Generated by tools/pyq-ingest/neet-assemble.js: add new papers with that tool, do not edit by hand. */\nwindow.${globalOf(g.sub, g.ch)}=[\n${all.map(x => JSON.stringify(x)).join(',\n')}\n];\n`;
  written.push([g.sub, g.ch, all.length, add.length]);
  if (WRITE) fs.writeFileSync(p, body);
}
const per = {}; for (const [s, c, n] of written) { (per[s] ||= []).push(`${c} ${n}`) }
console.log(`entries ${out.length} / expected ${expect}; gaps ${gaps.length ? gaps.join(',') : 'none'}; missing ${missing.length ? missing.join(',') : 'none'}`);
console.log(`diagram questions: ${out.filter(x => seen.get(x.e.pn)._needFig).length} still need a fig, ${out.filter(x => seen.get(x.e.pn)._needSfig).length} need a solution fig`);
for (const s of Object.keys(per)) console.log(`${s} (${per[s].reduce((a, t) => a + +t.split(' ').pop(), 0)}): ${per[s].join('; ')}`);
if (dups.length) console.log('duplicates skipped:', dups.join('; '));
if (problems.length) { console.log('PROBLEMS:\n' + problems.join('\n')); process.exit(1) }
console.log(WRITE ? `written ${written.length} chapter files` : 'dry run (add --write to write the files)');
