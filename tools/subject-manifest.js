/* Builds the small always-loaded index of the Botany, Zoology and Chemistry experiments.
   The packs run once here, in a sandbox, and only their plain data (titles, chapters, controls,
   presets) is kept; their drawing code ships in separate bundles that load in the background. */
'use strict';
const fs=require('fs'),path=require('path'),vm=require('vm');
// stands in for the 3D engine: any property, call or arithmetic on it just works
const any=()=>{const f=function(){};const p=new Proxy(f,{get:(t,k)=>k===Symbol.toPrimitive?()=>0:k==='then'?undefined:p,apply:()=>p,construct:()=>p});return p};
module.exports=function manifest(root,packs){
  const win={SimulationLessons:{},ExtraSimulations:[],PhysicsDraw:{draw(){},available:[]},PhysicaRenderExperiment(){},Physica3D:any()};
  win.window=win;const ctx=vm.createContext(win);
  for(const f of ['labkit.js','biokit.js'])vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),ctx,{filename:f});
  const out=[];
  for(const [key,files] of Object.entries(packs))for(const f of files){
    const before=win.ExtraSimulations.length;vm.runInContext(fs.readFileSync(path.join(root,f),'utf8'),ctx,{filename:f});
    for(const e of win.ExtraSimulations.slice(before)){
      // kept: what the library, search and shared links need; the lesson text arrives with the pack
      const {metrics,renderer,formula,observe,try:_t,draw,...data}=e;
      out.push({k:key,...JSON.parse(JSON.stringify(data))});
    }
  }
  const urls=Object.keys(packs).map(k=>`${k}:'__${k.toUpperCase()}_URL__'`).join(',');
  return `/* Generated by tools/subject-manifest.js: the index of the lazily loaded subject packs. */
(() => {
'use strict';
const M=JSON.parse(${JSON.stringify(JSON.stringify(out))});
const URL={${urls}},wait={},ids=new Map();
function load(k){return wait[k]||(wait[k]=new Promise((ok,no)=>{const s=document.createElement('script');s.src=URL[k];s.async=true;s.onload=ok;s.onerror=()=>{wait[k]=null;s.remove();no()};document.head.append(s)}))}
window.PhysicaLoadSubject=k=>URL[k]?load(k).catch(()=>{}):Promise.resolve();
for(const {k,...e} of M){ids.set(e.id,k);window.ExtraSimulations.push({...e,formula:'',observe:'',try:'',metrics:()=>[],lazy:k})}
// until its pack arrives, an experiment shows a quiet placeholder (normally the pack is already there)
const previous=window.PhysicsDraw.draw;
window.PhysicsDraw.draw=(c,id,p,t)=>{const k=ids.get(id);if(!k)return previous(c,id,p,t);load(k).catch(()=>{});c.save();c.fillStyle='#8ca6b9';c.font='600 15px system-ui,sans-serif';c.textAlign='center';c.fillText('Loading…',480,252);c.restore()};
window.PhysicsDraw.available.push(...ids.keys());
})();
`;
};
